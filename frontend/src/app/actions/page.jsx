"use client";
import { useRouter } from "next/navigation";
import { useBusiness } from "@/context/BusinessContext";
import { Target, Plus, ArrowRight, Info } from "lucide-react";
import { useMemo } from "react";

export default function ActionsPage() {
  const router = useRouter();
  const { isDemo, hasMLData, mlAnalytics, selected } = useBusiness();

  const actions = useMemo(() => {
    if (isDemo || !hasMLData) return [];
    const ins = mlAnalytics?.mlResults?.insights || {};
    return [
      ...(ins.recommendations || []).map((r) => ({ ...r, kind: "Recommendation" })),
      ...(ins.opportunities || []).map((o) => ({ ...o, kind: "Opportunity" })),
    ];
  }, [isDemo, hasMLData, mlAnalytics]);

  if (isDemo || !hasMLData) {
    return (
      <div className="q-page-shell">
        <h1 className="q-page-title">Next Best Actions</h1>
        <div style={{ maxWidth: 520, margin: "60px auto", textAlign: "center" }}>
          <Target size={40} style={{ opacity: 0.25, marginBottom: 16 }} />
          <h2 style={{ fontWeight: 700, fontSize: "1.25rem", marginBottom: 10 }}>{isDemo ? "Demo mode" : "No actions yet"}</h2>
          <p style={{ color: "var(--q-text-3)", lineHeight: 1.7, marginBottom: 24 }}>
            {isDemo ? "Next Best Actions come from your real data. Exit demo mode to see them." : "Upload sales data — the ML pipeline generates ranked, data-backed actions."}
          </p>
          <button onClick={() => router.push(isDemo ? "/businesses" : "/businesses/new")} className="q-btn q-btn-primary q-btn-sm" style={{ gap: 6 }}>
            <Plus size={14} /> {isDemo ? "Exit Demo" : "Add Business / Upload Data"}
          </button>
        </div>
      </div>
    );
  }

  const currency = selected?.currency || "USD";

  return (
    <div className="q-page-shell">
      <div className="q-page-header">
        <div style={{ display: "flex", alignItems: "center", gap: 10 }}>
          <Target size={20} color="#8B1A1A" />
          <div>
            <h1 className="q-page-title">Next Best Actions</h1>
            <p className="q-page-subtitle">
              {selected?.businessName} · ranked from your ML outputs — every action cites its evidence
            </p>
          </div>
        </div>
      </div>

      {actions.length === 0 ? (
        <div className="q-card" style={{ padding: "40px 24px", textAlign: "center" }}>
          <Target size={34} style={{ opacity: 0.25, marginBottom: 12 }} />
          <p style={{ color: "var(--q-text-3)", fontSize: "0.87rem" }}>No actions generated yet — upload more data or wait for the next analysis.</p>
        </div>
      ) : (
        <div style={{ display: "flex", flexDirection: "column", gap: 14 }}>
          {actions.map((a, i) => (
            <div key={i} className="q-card" style={{ padding: 20, display: "flex", gap: 16, alignItems: "flex-start" }}>
              <span style={{ width: 30, height: 30, borderRadius: 8, background: "#8B1A1A", color: "#fff", fontWeight: 800, fontSize: "0.85rem", display: "flex", alignItems: "center", justifyContent: "center", flexShrink: 0 }}>{i + 1}</span>
              <div style={{ flex: 1 }}>
                <div style={{ display: "flex", justifyContent: "space-between", flexWrap: "wrap", gap: 8, marginBottom: 6 }}>
                  <h3 style={{ fontWeight: 700, fontSize: "0.98rem" }}>{a.title}</h3>
                  <div style={{ display: "flex", gap: 6 }}>
                    <span className="q-badge q-badge-neutral">{a.kind}</span>
                    {a.severity && <span className={`q-badge ${a.severity === "high" ? "q-badge-danger" : a.severity === "medium" ? "q-badge-warning" : "q-badge-neutral"}`}>{a.severity}</span>}
                  </div>
                </div>
                <p style={{ fontSize: "0.85rem", color: "var(--q-text-3)", lineHeight: 1.6, marginBottom: 8 }}>{a.detail}</p>
                {a.metric && <div style={{ fontSize: "0.72rem", color: "var(--q-text-4)", fontFamily: "monospace" }}>evidence: {a.metric}</div>}
              </div>
              <button onClick={() => router.push("/simulator")} className="q-btn q-btn-ghost q-btn-sm" style={{ gap: 4, flexShrink: 0 }}>
                Simulate <ArrowRight size={13} />
              </button>
            </div>
          ))}
        </div>
      )}

      <p style={{ fontSize: "0.75rem", color: "var(--q-text-4)", marginTop: 18, display: "flex", alignItems: "center", gap: 6 }}>
        <Info size={12} /> Recommendations are generated by the rule engine from your actual metrics — revenue trend, margins, repeat rate, peak hours, anomalies and forecasts.
      </p>
    </div>
  );
}
