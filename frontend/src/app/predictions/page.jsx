"use client";
import { useRouter } from "next/navigation";
import { useBusiness } from "@/context/BusinessContext";
import {
  TrendingUp, DollarSign, ShoppingBag, Package, Info,
  ChevronRight, Plus, Award,
} from "lucide-react";
import {
  LineChart, Line, XAxis, YAxis, CartesianGrid, Tooltip,
  ResponsiveContainer, Legend, BarChart, Bar,
} from "recharts";

function EmptyState({ router, isDemo }) {
  return (
    <div className="q-page-shell">
      <h1 className="q-page-title">Predictions</h1>
      <div style={{ maxWidth: 520, margin: "60px auto", textAlign: "center" }}>
        <div style={{ fontSize: "3rem", marginBottom: 16, opacity: 0.3 }}>🔮</div>
        <h2 style={{ fontWeight: 700, fontSize: "1.375rem", marginBottom: 12 }}>
          {isDemo ? "Demo mode active" : "No forecast data yet"}
        </h2>
        <p style={{ color: "var(--q-text-3)", lineHeight: 1.7, marginBottom: 28 }}>
          {isDemo
            ? "Predictions are generated from your real business data. Exit demo mode and select a business with uploaded data."
            : "Sales, order-volume and item-demand forecasts are generated by the ML pipeline from your accumulated sales history. Upload a CSV/Excel file to enable predictions."}
        </p>
        <button onClick={() => router.push(isDemo ? "/businesses" : "/businesses/new")} className="q-btn q-btn-primary q-btn-sm" style={{ gap: 6 }}>
          <Plus size={14} /> {isDemo ? "Exit Demo & Choose Business" : "Add Business / Upload Data"}
        </button>
      </div>
    </div>
  );
}

const CONF_COLOR = { high: "#059669", medium: "#D97706", low: "#DC2626" };

function ConfidenceBadge({ evaln }) {
  if (!evaln?.confidence) return null;
  const c = CONF_COLOR[evaln.confidence] || "#6B7280";
  return (
    <span className="q-badge" style={{ background: c + "18", color: c, border: `1px solid ${c}40` }}>
      {evaln.confidence} confidence{evaln.confidence_score != null ? ` · ${Math.round(evaln.confidence_score * 100)}%` : ""}
    </span>
  );
}

export default function PredictionsPage() {
  const router = useRouter();
  const { isDemo, hasMLData, mlAnalytics, selected } = useBusiness();

  if (isDemo || !hasMLData) return <EmptyState router={router} isDemo={isDemo} />;

  const fc = mlAnalytics?.mlResults?.insights?.demand_forecast;
  const currency = selected?.currency || "USD";

  if (!fc?.available) {
    return (
      <div className="q-page-shell">
        <h1 className="q-page-title">Predictions</h1>
        <div className="q-card" style={{ padding: "40px 24px", textAlign: "center", maxWidth: 560, margin: "40px auto" }}>
          <Info size={36} style={{ opacity: 0.3, marginBottom: 14 }} />
          <h2 style={{ fontWeight: 700, marginBottom: 8 }}>Forecast unavailable</h2>
          <p style={{ color: "var(--q-text-3)", fontSize: "0.88rem" }}>{fc?.reason || "Insufficient dated sales history for forecasting."}</p>
        </div>
      </div>
    );
  }

  const freqLabel = fc.frequency === "daily" ? "day" : fc.frequency === "weekly" ? "week" : "month";
  const salesData = [
    ...(fc.history || []).map((h) => ({ period: h.period, actual: h.actual, forecast: null })),
    ...(fc.forecast || []).map((f) => ({ period: f.period, actual: null, forecast: f.forecast })),
  ];
  const orderData = fc.order_forecast
    ? [
      ...(fc.order_forecast.history || []).map((h) => ({ period: h.period, actual: h.actual, forecast: null })),
      ...(fc.order_forecast.forecast || []).map((f) => ({ period: f.period, actual: null, forecast: f.forecast })),
    ]
    : null;

  const tip = (v) => v != null ? `${currency} ${Number(v).toLocaleString(undefined, { maximumFractionDigits: 0 })}` : "—";
  const tipNum = (v) => v != null ? Number(v).toLocaleString(undefined, { maximumFractionDigits: 1 }) : "—";

  return (
    <div className="q-page-shell">
      <div className="q-page-header">
        <h1 className="q-page-title">Predictions</h1>
        <p className="q-page-subtitle">
          {selected?.businessName} · {fc.frequency} forecasts · generated {mlAnalytics?.processedAt ? new Date(mlAnalytics.processedAt).toLocaleString() : ""}
        </p>
      </div>

      {/* Forecast quality strip */}
      <div className="q-kpi-grid" style={{ marginBottom: 24 }}>
        {[
          { label: "Method", value: "Linear trend", icon: TrendingUp, color: "#2563EB" },
          { label: "Horizon", value: `${fc.horizon} ${freqLabel}s`, icon: CalendarIcon, color: "#7C3AED" },
          { label: "Last actual", value: fc.last_actual_period || "—", icon: Award, color: "#D97706" },
          { label: "Fit quality", value: fc.evaluation ? `${fc.evaluation.mape_pct}% MAPE` : "—", icon: Info, color: "#0891B2" },
        ].map((s) => (
          <div key={s.label} className="q-card" style={{ padding: "16px 18px", display: "flex", alignItems: "center", gap: 12 }}>
            <div style={{ width: 38, height: 38, borderRadius: 10, background: s.color + "18", display: "flex", alignItems: "center", justifyContent: "center", flexShrink: 0 }}>
              <s.icon size={17} style={{ color: s.color }} />
            </div>
            <div>
              <div style={{ fontSize: "0.72rem", color: "var(--q-text-4)", fontWeight: 600, textTransform: "uppercase", letterSpacing: "0.05em" }}>{s.label}</div>
              <div style={{ fontWeight: 700, fontSize: "1rem" }}>{s.value}</div>
            </div>
          </div>
        ))}
      </div>
      {fc.evaluation && (
        <div className="q-card" style={{ padding: "12px 18px", marginBottom: 24, display: "flex", alignItems: "center", gap: 10, flexWrap: "wrap" }}>
          <span style={{ fontSize: "0.82rem", color: "var(--q-text-3)" }}>Forecast confidence (in-sample):</span>
          <ConfidenceBadge evaln={fc.evaluation} />
          <span style={{ fontSize: "0.78rem", color: "var(--q-text-4)" }}>
            RMSE {fc.evaluation.rmse?.toLocaleString()} · MAE {fc.evaluation.mae?.toLocaleString()} · fitted on {fc.evaluation.fitted_points} periods
          </span>
        </div>
      )}

      {/* Sales forecast */}
      <div className="q-card" style={{ padding: 24, marginBottom: 24 }}>
        <div style={{ display: "flex", alignItems: "center", gap: 8, marginBottom: 4 }}>
          <DollarSign size={17} color="#2563EB" />
          <h3 style={{ fontWeight: 700, fontSize: "0.95rem" }}>Revenue Forecast</h3>
          <ConfidenceBadge evaln={fc.evaluation} />
        </div>
        <p style={{ fontSize: "0.78rem", color: "var(--q-text-4)", marginBottom: 14 }}>
          Actual (blue) vs predicted (green, dashed) — forecast starts {fc.last_actual_period ? `after ${fc.last_actual_period}` : "after latest data"}.
        </p>
        <ResponsiveContainer width="100%" height={280}>
          <LineChart data={salesData}>
            <CartesianGrid strokeDasharray="3 3" stroke="var(--q-border)" vertical={false} />
            <XAxis dataKey="period" tick={{ fontSize: 10, fill: "var(--q-text-4)" }} axisLine={false} tickLine={false} interval="preserveStartEnd" />
            <YAxis tick={{ fontSize: 11, fill: "var(--q-text-4)" }} axisLine={false} tickLine={false} width={60} tickFormatter={(v) => `${(v / 1000).toFixed(0)}k`} />
            <Tooltip formatter={(v, n) => [tip(v), n === "actual" ? "Actual" : "Forecast"]} contentStyle={{ borderRadius: 8, border: "1px solid var(--q-border)" }} />
            <Legend wrapperStyle={{ fontSize: 11 }} />
            <Line type="monotone" dataKey="actual" name="Actual" stroke="#2563EB" strokeWidth={2} dot={false} connectNulls />
            <Line type="monotone" dataKey="forecast" name="Forecast" stroke="#059669" strokeWidth={2} strokeDasharray="6 4" dot={{ r: 3 }} connectNulls />
          </LineChart>
        </ResponsiveContainer>
        {fc.forecast?.length > 0 && (
          <div style={{ display: "flex", gap: 8, marginTop: 10, flexWrap: "wrap" }}>
            {fc.forecast.slice(0, 5).map((f, i) => (
              <span key={i} className="q-badge q-badge-neutral">{f.period}: {tip(f.forecast)}</span>
            ))}
          </div>
        )}
      </div>

      {/* Order volume forecast */}
      {orderData && (
        <div className="q-card" style={{ padding: 24, marginBottom: 24 }}>
          <div style={{ display: "flex", alignItems: "center", gap: 8, marginBottom: 4 }}>
            <ShoppingBag size={17} color="#7C3AED" />
            <h3 style={{ fontWeight: 700, fontSize: "0.95rem" }}>Order-Volume Forecast</h3>
            <ConfidenceBadge evaln={fc.order_forecast?.evaluation} />
          </div>
          <p style={{ fontSize: "0.78rem", color: "var(--q-text-4)", marginBottom: 14 }}>
            Unique orders per {freqLabel} — actual vs predicted.
          </p>
          <ResponsiveContainer width="100%" height={240}>
            <LineChart data={orderData}>
              <CartesianGrid strokeDasharray="3 3" stroke="var(--q-border)" vertical={false} />
              <XAxis dataKey="period" tick={{ fontSize: 10, fill: "var(--q-text-4)" }} axisLine={false} tickLine={false} interval="preserveStartEnd" />
              <YAxis tick={{ fontSize: 11, fill: "var(--q-text-4)" }} axisLine={false} tickLine={false} width={45} />
              <Tooltip formatter={(v, n) => [tipNum(v), n === "actual" ? "Actual orders" : "Forecast orders"]} contentStyle={{ borderRadius: 8, border: "1px solid var(--q-border)" }} />
              <Legend wrapperStyle={{ fontSize: 11 }} />
              <Line type="monotone" dataKey="actual" name="Actual" stroke="#7C3AED" strokeWidth={2} dot={false} connectNulls />
              <Line type="monotone" dataKey="forecast" name="Forecast" stroke="#D97706" strokeWidth={2} strokeDasharray="6 4" dot={{ r: 3 }} connectNulls />
            </LineChart>
          </ResponsiveContainer>
        </div>
      )}

      {/* Item demand forecasts */}
      {(fc.item_demand_forecast || []).length > 0 && (
        <div className="q-card" style={{ padding: 24 }}>
          <div style={{ display: "flex", alignItems: "center", gap: 8, marginBottom: 14 }}>
            <Package size={17} color="#059669" />
            <h3 style={{ fontWeight: 700, fontSize: "0.95rem" }}>Menu-Item Demand Predictions</h3>
          </div>
          <p style={{ fontSize: "0.78rem", color: "var(--q-text-4)", marginBottom: 16 }}>
            Predicted units per {freqLabel} for your top items by volume — use for purchasing &amp; prep planning.
          </p>
          <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fill, minmax(280px, 1fr))", gap: 16 }}>
            {fc.item_demand_forecast.map((item) => {
              const chartData = [
                ...(item.history || []).slice(-14).map((h) => ({ period: h.period, actual: h.actual, forecast: null })),
                ...(item.forecast || []).map((f) => ({ period: f.period, actual: null, forecast: f.forecast })),
              ];
              const next = item.forecast?.[0];
              return (
                <div key={item.product} style={{ border: "1px solid var(--q-border)", borderRadius: 12, padding: 14 }}>
                  <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: 8 }}>
                    <span style={{ fontWeight: 700, fontSize: "0.88rem" }}>{item.product}</span>
                    <span className="q-badge q-badge-neutral">next: {next ? `${next.forecast} units` : "—"}</span>
                  </div>
                  <ResponsiveContainer width="100%" height={110}>
                    <BarChart data={chartData.slice(-16)}>
                      <XAxis dataKey="period" hide />
                      <YAxis hide />
                      <Tooltip formatter={(v, n) => [tipNum(v), n === "actual" ? "Actual" : "Forecast"]} contentStyle={{ borderRadius: 8, fontSize: 11 }} />
                      <Bar dataKey="actual" fill="#2563EB" radius={[2, 2, 0, 0]} />
                      <Bar dataKey="forecast" fill="#059669" radius={[2, 2, 0, 0]} />
                    </BarChart>
                  </ResponsiveContainer>
                  <div style={{ fontSize: "0.72rem", color: "var(--q-text-4)", marginTop: 6 }}>
                    {item.evaluation ? `${item.evaluation.confidence} confidence · ${item.evaluation.mape_pct}% MAPE` : ""}
                  </div>
                </div>
              );
            })}
          </div>
        </div>
      )}

      <p style={{ fontSize: "0.75rem", color: "var(--q-text-4)", marginTop: 16, display: "flex", alignItems: "center", gap: 6 }}>
        <Info size={12} /> Predictions are statistical trend projections from your uploaded history — not guarantees. Simulated scenarios are labelled separately on the Decision Simulator.
        <button onClick={() => router.push("/simulator")} className="q-btn q-btn-ghost q-btn-sm" style={{ marginLeft: "auto", gap: 4 }}>
          Open Simulator <ChevronRight size={13} />
        </button>
      </p>
    </div>
  );
}

function CalendarIcon(props) {
  return <svg xmlns="http://www.w3.org/2000/svg" width="17" height="17" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" {...props}><rect x="3" y="4" width="18" height="18" rx="2" /><line x1="16" y1="2" x2="16" y2="6" /><line x1="8" y1="2" x2="8" y2="6" /><line x1="3" y1="10" x2="21" y2="10" /></svg>;
}
